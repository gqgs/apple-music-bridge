"""Install an opt-in user unit. Never invoke systemctl, login, or runtime setup."""

import os
import re
import shutil
import sys
import tempfile
from pathlib import Path

from .model import PlayerError

UNIT_NAME = "apple-music-bridge.service"


def quote(value, *, command=False):
    """Quote one systemd word, not a shell word; reject directive/control injection."""
    value = str(value)
    if any(ord(char) < 32 or ord(char) == 127 for char in value):
        raise PlayerError("Service settings must not contain control characters.")
    value = value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    if command:
        value = value.replace("$", "$$")
    return '"' + value + '"'


def unit_text(args, root):
    """Freeze paths at installation time, including legacy and custom XDG defaults."""
    if not re.fullmatch(r"[a-z]{2}", args.country):
        raise PlayerError("Service storefront must be a two-letter lowercase country code.")
    if not 1 <= args.port <= 65535 or not 1 <= args.cache_gib <= 1024:
        raise PlayerError("Service port or cache size is outside the supported range.")
    probe = shutil.which("ffprobe")
    if not probe:
        raise PlayerError("Install ffprobe before installing the user service.")
    env = shutil.which("env", path=os.defpath)
    if not env:
        raise PlayerError("Install the standard env utility before installing the user service.")
    # Do not resolve the interpreter symlink: that would bypass the virtualenv.
    python = Path(sys.executable).absolute()
    if "=" in str(python):
        raise PlayerError("The service Python path cannot contain an equals sign.")
    cache = args.cache or (
        Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "apple-music-bridge"
    )
    command = [
        env,
        "--",
        python,
        "-u",
        "-m",
        "apple_music_player.cli",
        "serve",
        "--runtime-root",
        Path(root).absolute(),
        "--auth-file",
        args.auth_file.absolute(),
        "--cache",
        cache.absolute(),
        "--cache-gib",
        args.cache_gib,
        "--country",
        args.country,
        "--quality",
        args.quality,
        "--port",
        args.port,
    ]
    if args.diagnostics:
        command.append("--diagnostics")
    # env execs Python without a shell, allowing valid Python paths that systemd
    # rejects in its first executable word (for example quotes or backslashes).
    # Capture only executable search paths, never the shell's credentials or other
    # environment. A nonstandard ffprobe and the chosen venv work without activation.
    if any(":" in str(directory) for directory in (python.parent, Path(probe).absolute().parent)):
        raise PlayerError("Service executable directories cannot contain a colon.")
    path = ":".join(
        dict.fromkeys(
            [str(python.parent), str(Path(probe).absolute().parent), *os.defpath.split(os.pathsep)]
        )
    )
    return "\n".join(
        [
            "# Generated by apple-music-bridge install-service. Contains paths, not credentials.",
            "[Unit]",
            "Description=Local Apple Music OpenSubsonic bridge",
            "StartLimitIntervalSec=120",
            "StartLimitBurst=5",
            "",
            "[Service]",
            "Type=exec",
            "ExecStart="
            + " ".join(quote(word, command=index > 0) for index, word in enumerate(command)),
            "Environment=" + quote("PATH=" + path),
            "WorkingDirectory=%h",
            "UMask=0077",
            "StandardInput=null",
            "Restart=on-failure",
            "RestartSec=10",
            # Let the bridge send SIGINT to its owned rootless runtime first.
            # If it gets stuck, systemd kills the entire remaining cgroup.
            "KillMode=mixed",
            "TimeoutStopSec=30",
            "",
            "[Install]",
            "WantedBy=default.target",
            "",
        ]
    )


def install(args, root):
    if sys.platform != "linux" or os.geteuid() == 0:
        raise PlayerError("Install the service on Linux as your normal user, never with sudo.")
    content = unit_text(args, root)  # Validate before touching the filesystem.
    directory = (
        Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "systemd" / "user"
    ).absolute()
    directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    if directory.stat().st_uid != os.getuid():
        raise PlayerError("The systemd user directory must belong to your user.")
    target = directory / UNIT_NAME
    if target.is_symlink() or (target.exists() and not args.replace):
        raise PlayerError("Service file already exists. Review it before using --replace.")
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=directory, delete=False
        ) as f:
            temporary = Path(f.name)
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        if args.replace:
            os.replace(temporary, target)
        else:
            # Exclusive creation, even if another installer raced the initial check.
            os.link(temporary, target)
    finally:
        if temporary:
            temporary.unlink(missing_ok=True)
    print("User service installed; it has not been enabled or started.")
    print("Run: systemctl --user daemon-reload")
    print("Then: systemctl --user enable --now " + UNIT_NAME)
    return 0
